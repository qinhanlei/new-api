package service

import (
	"context"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/QuantumNous/new-api/common"
	"github.com/QuantumNous/new-api/model"
	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/aws/signer/v4"
)

type AssetStore interface {
	Backend() string
	Put(context.Context, string, io.Reader, int64, string) error
	Presign(context.Context, string) (string, error)
	Delete(context.Context, string) error
}

type s3AssetStore struct {
	endpoint    *url.URL
	bucket      string
	region      string
	credentials aws.Credentials
	ttl         time.Duration
	client      *http.Client
}

func assetStorageBackend() string {
	backend := os.Getenv("ASSET_STORAGE")
	if backend == "" {
		backend = model.AssetStorageLocal
		// Preserve deployments configured before local storage was available.
		// Incomplete S3 configuration must fail instead of changing the target.
		for _, name := range []string{"ASSET_S3_ENDPOINT", "ASSET_S3_BUCKET", "ASSET_S3_REGION", "ASSET_S3_ACCESS_KEY_ID", "ASSET_S3_SECRET_ACCESS_KEY", "ASSET_S3_SESSION_TOKEN", "ASSET_S3_URL_TTL_SECONDS"} {
			if os.Getenv(name) != "" {
				backend = model.AssetStorageS3
				break
			}
		}
	}
	return backend
}

// InitAssetStorage validates the selected backend without creating a local
// store on slaves. Invalid S3 configuration must still fail startup.
func InitAssetStorage() error {
	if !common.AssetLibraryEnabled {
		return nil
	}
	backend := assetStorageBackend()
	if backend == model.AssetStorageLocal && !common.IsMasterNode {
		return nil
	}
	_, err := GetAssetStoreForBackend(backend)
	return err
}

// GetAssetStore is separate from task artifacts: material originals must remain
// retrievable after the original upload URL expires.
func GetAssetStore() (AssetStore, error) {
	return GetAssetStoreForBackend(assetStorageBackend())
}

// GetAssetStoreForBackend resolves persisted locations, never the current write
// default. Empty locations are legacy records from the original S3-only release.
func GetAssetStoreForBackend(backend string) (AssetStore, error) {
	if !common.AssetLibraryEnabled {
		return nil, ErrAssetStorageUnavailable
	}
	switch backend {
	case model.AssetStorageLocal:
		return newLocalAssetStore(true)
	case "", model.AssetStorageS3:
	default:
		return nil, ErrAssetStorageUnavailable
	}
	endpoint, err := url.Parse(strings.TrimRight(os.Getenv("ASSET_S3_ENDPOINT"), "/"))
	bucket := os.Getenv("ASSET_S3_BUCKET")
	key, secret := os.Getenv("ASSET_S3_ACCESS_KEY_ID"), os.Getenv("ASSET_S3_SECRET_ACCESS_KEY")
	if err != nil || endpoint.Host == "" || endpoint.Scheme != "https" || endpoint.User != nil || endpoint.RawQuery != "" || endpoint.Fragment != "" || bucket == "" || strings.ContainsAny(bucket, "/\\") || key == "" || secret == "" {
		return nil, ErrAssetStorageUnavailable
	}
	region := os.Getenv("ASSET_S3_REGION")
	if region == "" {
		region = "us-east-1"
	}
	ttl := int64(24 * 60 * 60)
	if configured := os.Getenv("ASSET_S3_URL_TTL_SECONDS"); configured != "" {
		ttl, err = strconv.ParseInt(configured, 10, 64)
		if err != nil || ttl < 3*60*60 || ttl > 7*24*60*60 {
			return nil, ErrAssetStorageUnavailable
		}
	}
	return &s3AssetStore{
		endpoint: endpoint, bucket: bucket, region: region,
		credentials: aws.Credentials{AccessKeyID: key, SecretAccessKey: secret, SessionToken: os.Getenv("ASSET_S3_SESSION_TOKEN")},
		ttl:         time.Duration(ttl) * time.Second,
		client:      &http.Client{Timeout: 5 * time.Minute, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }},
	}, nil
}

func (*s3AssetStore) Backend() string { return model.AssetStorageS3 }

func (s *s3AssetStore) request(ctx context.Context, method, key string, body io.Reader) (*http.Request, error) {
	// Keys are generated by the catalog, never accepted from clients.
	if key == "" || strings.Contains(key, "..") || strings.HasPrefix(key, "/") {
		return nil, fmt.Errorf("invalid asset object key")
	}
	target := *s.endpoint
	target.Path = strings.TrimRight(target.Path, "/") + "/" + s.bucket + "/" + key
	target.RawPath = ""
	return http.NewRequestWithContext(ctx, method, target.String(), body)
}

func (s *s3AssetStore) Put(ctx context.Context, key string, src io.Reader, size int64, mime string) error {
	request, err := s.request(ctx, http.MethodPut, key, src)
	if err != nil {
		return err
	}
	request.ContentLength = size
	request.Header.Set("Content-Type", mime)
	request.Header.Set("X-Amz-Content-Sha256", "UNSIGNED-PAYLOAD")
	// A source key is immutable, even if an upload is retried by an operator.
	request.Header.Set("If-None-Match", "*")
	if err := v4.NewSigner().SignHTTP(ctx, s.credentials, request, "UNSIGNED-PAYLOAD", "s3", s.region, time.Now(), func(o *v4.SignerOptions) { o.DisableURIPathEscaping = true }); err != nil {
		return err
	}
	response, err := s.client.Do(request)
	if err != nil {
		return ErrAssetStorageUnavailable
	}
	defer response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return ErrAssetStorageUnavailable
	}
	return nil
}

func (s *s3AssetStore) Presign(ctx context.Context, key string) (string, error) {
	request, err := s.request(ctx, http.MethodGet, key, nil)
	if err != nil {
		return "", err
	}
	query := request.URL.Query()
	query.Set("X-Amz-Expires", strconv.FormatInt(int64(s.ttl/time.Second), 10))
	request.URL.RawQuery = query.Encode()
	signed, _, err := v4.NewSigner().PresignHTTP(ctx, s.credentials, request, "UNSIGNED-PAYLOAD", "s3", s.region, time.Now(), func(o *v4.SignerOptions) { o.DisableURIPathEscaping = true })
	return signed, err
}

func (s *s3AssetStore) Delete(ctx context.Context, key string) error {
	request, err := s.request(ctx, http.MethodDelete, key, nil)
	if err != nil {
		return err
	}
	const emptyHash = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
	request.Header.Set("X-Amz-Content-Sha256", emptyHash)
	if err := v4.NewSigner().SignHTTP(ctx, s.credentials, request, emptyHash, "s3", s.region, time.Now(), func(o *v4.SignerOptions) { o.DisableURIPathEscaping = true }); err != nil {
		return err
	}
	response, err := s.client.Do(request)
	if err != nil {
		return ErrAssetStorageUnavailable
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusNotFound && (response.StatusCode < 200 || response.StatusCode >= 300) {
		return ErrAssetStorageUnavailable
	}
	return nil
}
